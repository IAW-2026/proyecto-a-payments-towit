import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { ClerkProvider } from '@clerk/nextjs'
import { auth } from "@clerk/nextjs/server";
import Header from "../components/Header";
import AdminHeaderDropdown from "@/components/admin/AdminHeaderDropdown";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {

  const { sessionClaims } = await auth();
  const isAdmin = sessionClaims?.role === "admin";

  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <ClerkProvider>
        <body className="min-h-full flex flex-col bg-gray-50 overflow-x-hidden">
          <Header adminMenuSlot={isAdmin ? <AdminHeaderDropdown /> : null} />
          <main className="flex-1 bg-white">{children}</main>
        </body>
      </ClerkProvider>
    </html>
  );
}